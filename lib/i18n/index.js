export function getI18nDict(lang = DEFAULT_LANG, domain) {
  const normalizedLang = SUPPORTED_LANGS.includes(lang) ? lang : DEFAULT_LANG;
  const languagePack = translations[normalizedLang] || translations[DEFAULT_LANG] || {};

  if (!domain) return languagePack;

  const fallbackPack = translations[DEFAULT_LANG] || {};
  return languagePack[domain] || fallbackPack[domain] || {};
}

export function getI18nText(lang, domain, key, fallback = '') {
  const dict = getI18nDict(lang, domain);
  const fallbackDict = getI18nDict(DEFAULT_LANG, domain);
  return dict[key] || fallbackDict[key] || fallback;
}
